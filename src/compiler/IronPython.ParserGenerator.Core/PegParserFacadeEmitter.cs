using System;
using System.Text;

namespace IronPython.ParserGenerator {
    public static class PegParserFacadeEmitter {
        public static string Emit(string namespaceName, string className, string descriptorsClassName) {
            if (namespaceName == null) throw new ArgumentNullException(nameof(namespaceName));
            if (className == null) throw new ArgumentNullException(nameof(className));
            if (descriptorsClassName == null) throw new ArgumentNullException(nameof(descriptorsClassName));

            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("#nullable enable");
            source.AppendLine("using IronPython.Compiler.Syntax;");
            source.AppendLine();
            source.Append("namespace ").Append(namespaceName).AppendLine(" {");
            source.Append("    public static class ").Append(className).AppendLine(" {");
            source.AppendLine("        public const string ModuleStartRule = \"file\";");
            source.AppendLine("        public const string EvalStartRule = \"eval\";");
            source.AppendLine("        public const string InteractiveStartRule = \"interactive\";");
            source.AppendLine();
            EmitParseMethod(source, "ParseModule", "Module");
            EmitParseMethod(source, "ParseEval", "Eval");
            EmitParseMethod(source, "ParseInteractive", "Interactive");
            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        private static void EmitParseMethod(StringBuilder source, string methodName, string modeName) {
            source.Append("        public static PegParseResult ")
                .Append(methodName)
                .AppendLine("(");
            source.AppendLine("            IPegTokenSource tokens,");
            source.AppendLine("            IPegActionHandler? actions = null,");
            source.AppendLine("            IPegInvalidRuleHandler? invalidRuleHandler = null,");
            source.AppendLine("            PegParserOptions? options = null) {");
            source.Append("            return new PegParser(")
                .Append(DescriptorsClassName)
                .Append(".Rules, tokens, actions, invalidRuleHandler, options).Parse(")
                .Append(modeName)
                .AppendLine("StartRule);");
            source.AppendLine("        }");
            source.AppendLine();
        }

        private static string DescriptorsClassName => "PythonGrammarDescriptors";
    }
}
