using System;
using System.Linq;
using System.Text;

namespace IronPython.ParserGenerator {
    public static class MiniGrammarEmitter {
        public static string Emit(GrammarDefinition grammar, string namespaceName, string className) {
            if (grammar == null) throw new ArgumentNullException(nameof(grammar));
            if (grammar.Rules.Count != 1) {
                throw new FormatException("The initial generator slice expects exactly one rule.");
            }

            var rule = grammar.Rules[0];
            if (rule.Name != "start" ||
                rule.Items.Count != 4 ||
                rule.Items[0].Kind != GrammarItemKind.Token ||
                rule.Items[0].Value != "NAME" ||
                rule.Items[1].Kind != GrammarItemKind.Literal ||
                rule.Items[1].Value != "=" ||
                rule.Items[2].Kind != GrammarItemKind.Token ||
                rule.Items[2].Value != "INTEGER" ||
                rule.Items[3].Kind != GrammarItemKind.EndOfFile) {
                throw new FormatException("The initial generator slice expects: start: NAME \"=\" INTEGER EOF;");
            }

            return $$"""
                // <auto-generated />
                #nullable enable
                using System;
                using System.Globalization;

                namespace {{namespaceName}} {
                    public sealed class MiniParseResult {
                        public MiniParseResult(string name, int value) {
                            Name = name;
                            Value = value;
                        }

                        public string Name { get; }
                        public int Value { get; }
                    }

                    public static class {{className}} {
                        public static MiniParseResult ParseAssignment(string source) {
                            if (source == null) throw new ArgumentNullException(nameof(source));
                            int position = 0;
                            SkipWhitespace(source, ref position);
                            string name = ReadIdentifier(source, ref position);
                            SkipWhitespace(source, ref position);
                            Expect(source, ref position, '=');
                            SkipWhitespace(source, ref position);
                            int value = ReadInteger(source, ref position);
                            SkipWhitespace(source, ref position);
                            if (position != source.Length) {
                                throw new FormatException($"Unexpected character '{source[position]}'.");
                            }
                            return new MiniParseResult(name, value);
                        }

                        private static void SkipWhitespace(string source, ref int position) {
                            while (position < source.Length && char.IsWhiteSpace(source[position])) position++;
                        }

                        private static string ReadIdentifier(string source, ref int position) {
                            int start = position;
                            if (position >= source.Length || (source[position] != '_' && !char.IsLetter(source[position]))) {
                                throw new FormatException("Expected identifier.");
                            }
                            position++;
                            while (position < source.Length && (source[position] == '_' || char.IsLetterOrDigit(source[position]))) position++;
                            return source.Substring(start, position - start);
                        }

                        private static int ReadInteger(string source, ref int position) {
                            int start = position;
                            while (position < source.Length && char.IsDigit(source[position])) position++;
                            if (start == position) throw new FormatException("Expected integer.");
                            return int.Parse(source.Substring(start, position - start), CultureInfo.InvariantCulture);
                        }

                        private static void Expect(string source, ref int position, char value) {
                            if (position >= source.Length || source[position] != value) {
                                throw new FormatException($"Expected '{value}'.");
                            }
                            position++;
                        }
                    }
                }
                """;
        }
    }
}
