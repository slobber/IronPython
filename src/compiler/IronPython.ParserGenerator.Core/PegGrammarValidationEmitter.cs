using System;
using System.Collections.Generic;
using System.Linq;

namespace IronPython.ParserGenerator {
    public static class PegGrammarValidationEmitter {
        public static string Emit(PegGrammar grammar, string namespaceName, string className) {
            if (grammar == null) throw new ArgumentNullException(nameof(grammar));

            string startRules = string.Empty;
            var invalidRules = new List<string>();
            foreach (PegGrammarRule rule in grammar.Rules) {
                if (rule.Name == "file" || rule.Name == "interactive" || rule.Name == "eval" || rule.Name == "func_type") {
                    if (startRules.Length > 0) startRules += ", ";
                    startRules += $"\"{rule.Name}\"";
                }
                if (rule.Name.StartsWith("invalid_", StringComparison.Ordinal)) {
                    invalidRules.Add(rule.Name);
                }
            }

            string invalidRuleNames = string.Join(", ", invalidRules.Select(rule => $"\"{rule}\""));
            int versionCheckCount = PegActionMetadata.CountVersionChecks(grammar);

            return $$"""
                // <auto-generated />
                namespace {{namespaceName}} {
                    public static class {{className}} {
                        public const bool Validated = true;
                        public const int RuleCount = {{grammar.Rules.Count}};
                        public const int InvalidRuleCount = {{invalidRules.Count}};
                        public const int VersionCheckCount = {{versionCheckCount}};
                        public static readonly string[] StartRules = new[] { {{startRules}} };
                        public static readonly string[] InvalidRules = new[] { {{invalidRuleNames}} };
                    }
                }
                """;
        }
    }
}
