using System;
using System.Collections.Generic;
using System.Text;

namespace IronPython.ParserGenerator {
    public static class PegActionCatalogEmitter {
        public static string Emit(PegGrammar grammar, string namespaceName, string className) {
            if (grammar == null) throw new ArgumentNullException(nameof(grammar));

            var alternativeIds = new List<string>();
            var actionIds = new List<string>();
            foreach (PegGrammarRule rule in grammar.Rules) {
                for (int i = 0; i < rule.Alternatives.Count; i++) {
                    string path = rule.Name + "." + i;
                    alternativeIds.Add(path);
                    CollectAlternative(rule.Alternatives[i], path, actionIds);
                }
            }

            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.Append("namespace ").Append(namespaceName).AppendLine(" {");
            source.Append("    public static class ").Append(className).AppendLine(" {");
            EmitArray(source, "AlternativeIds", alternativeIds);
            EmitArray(source, "ActionIds", actionIds);
            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        private static void CollectAlternative(PegAlternative alternative, string path, List<string> actionIds) {
            if (alternative.Action is not null) {
                actionIds.Add(path);
            }
            for (int i = 0; i < alternative.Elements.Count; i++) {
                CollectElement(alternative.Elements[i], path + "." + i, actionIds);
            }
        }

        private static void CollectElement(PegElement element, string path, List<string> actionIds) {
            if (element.Child is not null) {
                CollectElement(element.Child, path + ".child", actionIds);
            }
            if (element.Separator is not null) {
                CollectElement(element.Separator, path + ".separator", actionIds);
            }
            if (element.Alternatives is not null) {
                for (int i = 0; i < element.Alternatives.Count; i++) {
                    CollectAlternative(element.Alternatives[i], path + "." + i, actionIds);
                }
            }
        }

        private static void EmitArray(StringBuilder source, string name, List<string> values) {
            source.Append("        public static readonly string[] ")
                .Append(name)
                .AppendLine(" = new string[] {");
            foreach (string value in values) {
                source.Append("            \"").Append(Escape(value)).AppendLine("\",");
            }
            source.AppendLine("        };");
        }

        private static string Escape(string value) {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }
    }
}
