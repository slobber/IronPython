using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace IronPython.ParserGenerator {
    public static class PegActionDispatcherEmitter {
        public static string Emit(PegGrammar grammar, string namespaceName, string className) {
            if (grammar == null) throw new ArgumentNullException(nameof(grammar));

            var actionIds = new List<string>();
            foreach (PegGrammarRule rule in grammar.Rules) {
                for (int i = 0; i < rule.Alternatives.Count; i++) {
                    CollectAlternative(rule.Alternatives[i], rule.Name + "." + i, actionIds);
                }
            }

            var methodNames = actionIds.Select(ActionMethodName).ToArray();
            if (actionIds.Distinct(StringComparer.Ordinal).Count() != actionIds.Count) {
                throw new InvalidOperationException("Python grammar contains duplicate action identifiers.");
            }
            if (methodNames.Distinct(StringComparer.Ordinal).Count() != methodNames.Length) {
                throw new InvalidOperationException("Python grammar action identifiers collide after C# method-name encoding.");
            }

            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("#nullable enable");
            source.AppendLine("using System;");
            source.AppendLine("using System.Collections.Generic;");
            source.AppendLine("using IronPython.Compiler.Syntax;");
            source.AppendLine();
            source.Append("namespace ").Append(namespaceName).AppendLine(" {");
            source.Append("    public partial class ").Append(className).AppendLine(" : IPegActionHandler {");
            source.AppendLine("        public object? Invoke(PegActionContext context, PegActionArguments arguments) {");
            source.AppendLine("            switch (context.ActionId) {");
            for (int i = 0; i < actionIds.Count; i++) {
                source.Append("                case \"")
                    .Append(Escape(actionIds[i]))
                    .Append("\": return ")
                    .Append(methodNames[i])
                    .AppendLine("(context, arguments);");
            }
            source.AppendLine("                default:");
            source.AppendLine("                    throw new KeyNotFoundException(\"No typed C# handler exists for PEG action '\" + context.ActionId + \"'.\");");
            source.AppendLine("            }");
            source.AppendLine("        }");
            source.AppendLine();

            for (int i = 0; i < actionIds.Count; i++) {
                source.Append("        public virtual object? ")
                    .Append(methodNames[i])
                    .Append("(PegActionContext context, PegActionArguments arguments) => arguments; // ")
                    .AppendLine(EscapeComment(actionIds[i]));
            }
            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        internal static string ActionMethodName(string actionId) {
            var source = new StringBuilder("Handle_");
            foreach (char character in actionId) {
                source.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
            }
            return source.ToString();
        }

        private static void CollectAlternative(PegAlternative alternative, string path, List<string> actionIds) {
            if (alternative.Action is not null) {
                actionIds.Add(path);
            }
            for (int i = 0; i < alternative.Elements.Count; i++) {
                CollectElement(alternative.Elements[i], path + "." + i, actionIds);
            }
        }

        private static void CollectElement(PegElement element, string path, List<string> actionIds) {
            if (element.Child is not null) {
                CollectElement(element.Child, path + ".child", actionIds);
            }
            if (element.Separator is not null) {
                CollectElement(element.Separator, path + ".separator", actionIds);
            }
            if (element.Alternatives is not null) {
                for (int i = 0; i < element.Alternatives.Count; i++) {
                    CollectAlternative(element.Alternatives[i], path + "." + i, actionIds);
                }
            }
        }

        private static string Escape(string value) {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

        private static string EscapeComment(string value) {
            return value.Replace("\r", " ").Replace("\n", " ");
        }
    }
}
