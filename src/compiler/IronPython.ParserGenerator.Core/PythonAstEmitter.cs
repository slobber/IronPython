using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace IronPython.ParserGenerator {
    public static class PythonAstEmitter {
        private static readonly HashSet<string> CSharpKeywords = new HashSet<string>(StringComparer.Ordinal) {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
            "checked", "class", "const", "continue", "decimal", "default", "delegate", "do",
            "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
            "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
            "interface", "internal", "is", "lock", "long", "namespace", "new", "null",
            "object", "operator", "out", "override", "params", "private", "protected",
            "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof",
            "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true",
            "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using",
            "virtual", "void", "volatile", "while"
        };

        private static readonly IReadOnlyDictionary<string, string> BaseTypeNames =
            new Dictionary<string, string>(StringComparer.Ordinal) {
                ["mod"] = "ModBase",
                ["stmt"] = "Stmt",
                ["expr"] = "ExprBase",
                ["expr_context"] = "ExprContext",
                ["boolop"] = "BoolOpKind",
                ["operator"] = "OperatorKind",
                ["unaryop"] = "UnaryOpKind",
                ["cmpop"] = "CompareOpKind",
                ["excepthandler"] = "ExceptHandlerBase",
                ["pattern"] = "Pattern",
                ["type_ignore"] = "TypeIgnoreBase",
                ["type_param"] = "TypeParamBase"
            };

        public static string Emit(AsdlModule module, string namespaceName) {
            if (module == null) throw new ArgumentNullException(nameof(module));
            if (namespaceName == null) throw new ArgumentNullException(nameof(namespaceName));

            var types = module.Types.ToDictionary(type => type.Name, StringComparer.Ordinal);
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("#nullable enable");
            source.AppendLine("using System;");
            source.AppendLine("using System.Collections.Generic;");
            source.AppendLine("using System.Linq;");
            source.AppendLine();
            source.Append("namespace ").Append(namespaceName).AppendLine(" {");

            foreach (AsdlTypeDefinition type in module.Types) {
                EmitType(source, type, types);
            }
            EmitSchema(source, module, types);
            EmitFactory(source, module, types);
            EmitInterop(source);

            source.AppendLine("}");
            return source.ToString();
        }

        private static void EmitType(
            StringBuilder source,
            AsdlTypeDefinition type,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            if (type.IsProduct) {
                EmitConcreteNode(
                    source,
                    type.Name,
                    BaseClassName(type.Name),
                    "PythonAstNode",
                    type.Name,
                    type.Name,
                    type.ProductFields,
                    type.Attributes,
                    types);
                return;
            }

            string baseClass = BaseClassName(type.Name);
            source.Append("    public abstract class ").Append(baseClass).AppendLine(" : PythonAstNode {");
            source.Append("        protected ").Append(baseClass).AppendLine("(");
            source.AppendLine("            string kind,");
            source.AppendLine("            int? lineNumber,");
            source.AppendLine("            int? columnOffset,");
            source.AppendLine("            int? endLineNumber,");
            source.AppendLine("            int? endColumnOffset)");
            source.AppendLine("            : base(kind, lineNumber, columnOffset, endLineNumber, endColumnOffset) { }");
            source.AppendLine("    }");
            source.AppendLine();

            foreach (AsdlConstructor constructor in type.Constructors) {
                EmitConcreteNode(
                    source,
                    constructor.Name,
                    constructor.Name,
                    baseClass,
                    constructor.Name,
                    constructor.Name,
                    constructor.Fields,
                    type.Attributes,
                    types);
            }
        }

        private static void EmitConcreteNode(
            StringBuilder source,
            string className,
            string declarationName,
            string baseClass,
            string nodeKind,
            string metadataName,
            IReadOnlyList<AsdlField> fields,
            IReadOnlyList<AsdlField> attributes,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            source.Append("    public sealed class ").Append(declarationName)
                .Append(" : ").Append(baseClass).AppendLine(" {");
            source.Append("        public ").Append(declarationName).AppendLine("(");

            var parameters = new List<string>();
            foreach (AsdlField field in fields) {
                parameters.Add("            " + ClrType(field, types) + " " + EscapeIdentifier(field.Name));
            }
            foreach (AsdlField attribute in attributes) {
                parameters.Add("            " + ClrType(attribute, types) + " " + EscapeIdentifier(attribute.Name));
            }
            for (int i = 0; i < parameters.Count; i++) {
                source.Append(parameters[i]).Append(i + 1 == parameters.Count ? string.Empty : ",").AppendLine();
            }

            source.Append("        ) : base(")
                .Append(Quote(nodeKind)).Append(", ")
                .Append(AttributeArgument(attributes, "lineno")).Append(", ")
                .Append(AttributeArgument(attributes, "col_offset")).Append(", ")
                .Append(AttributeArgument(attributes, "end_lineno")).Append(", ")
                .Append(AttributeArgument(attributes, "end_col_offset")).AppendLine(") {");

            foreach (AsdlField field in fields) {
                string parameter = EscapeIdentifier(field.Name);
                string property = PropertyName(field.Name);
                if (RequiresNullCheck(field, types)) {
                    source.Append("            ").Append(property).Append(" = ").Append(parameter)
                        .Append(" ?? throw new ArgumentNullException(nameof(").Append(parameter).AppendLine("));");
                } else {
                    source.Append("            ").Append(property).Append(" = ").Append(parameter).AppendLine(";");
                }
            }
            source.AppendLine("        }");
            source.AppendLine();

            foreach (AsdlField field in fields) {
                source.Append("        public ").Append(ClrType(field, types)).Append(' ')
                    .Append(PropertyName(field.Name)).AppendLine(" { get; }");
            }
            if (fields.Count > 0) source.AppendLine();

            source.AppendLine("        public override IReadOnlyList<AstFieldValue> GetFields() {");
            source.AppendLine("            return new AstFieldValue[] {");
            foreach (AsdlField field in fields) {
                source.Append("                new AstFieldValue(")
                    .Append(Quote(field.Name)).Append(", ")
                    .Append(PropertyName(field.Name)).AppendLine("),");
            }
            foreach (AsdlField attribute in attributes) {
                source.Append("                new AstFieldValue(")
                    .Append(Quote(attribute.Name)).Append(", ")
                    .Append(AttributePropertyName(attribute.Name)).AppendLine("),");
            }
            source.AppendLine("            };");
            source.AppendLine("        }");
            source.AppendLine();

            source.AppendLine("        public override void WalkChildren(PythonAstWalker walker) {");
            foreach (AsdlField field in fields) {
                EmitWalkField(source, field, types);
            }
            source.AppendLine("        }");
            source.AppendLine("    }");
            source.AppendLine();
        }

        private static void EmitWalkField(
            StringBuilder source,
            AsdlField field,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            if (!IsAstReference(field.TypeName, types)) return;
            string property = PropertyName(field.Name);
            if (field.Sequence) {
                source.Append("            foreach (var item in ").Append(property).AppendLine(") {");
                source.AppendLine("                walker.Visit(item);");
                source.AppendLine("            }");
            } else {
                source.Append("            walker.Visit(").Append(property).AppendLine(");");
            }
        }

        private static void EmitSchema(
            StringBuilder source,
            AsdlModule module,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            source.AppendLine("    public static class PythonAstSchema {");
            source.AppendLine("        public static IReadOnlyDictionary<string, AstTypeMetadata> Types { get; } = Create();");
            source.AppendLine();
            source.AppendLine("        private static IReadOnlyDictionary<string, AstTypeMetadata> Create() {");
            source.AppendLine("            var result = new Dictionary<string, AstTypeMetadata>(StringComparer.Ordinal);");

            foreach (AsdlTypeDefinition type in module.Types) {
                if (type.IsProduct) {
                    EmitSchemaEntry(
                        source,
                        type.Name,
                        type.Name,
                        BaseClassName(type.Name),
                        type.ProductFields,
                        type.Attributes,
                        types);
                } else {
                    foreach (AsdlConstructor constructor in type.Constructors) {
                        EmitSchemaEntry(
                            source,
                            constructor.Name,
                            type.Name,
                            BaseClassName(type.Name),
                            constructor.Fields,
                            type.Attributes,
                            types);
                    }
                }
            }

            source.AppendLine("            return result;");
            source.AppendLine("        }");
            source.AppendLine("    }");
        }

        private static void EmitInterop(StringBuilder source) {
            source.AppendLine("    public static class PythonAstInterop {");
            source.AppendLine("        public static IReadOnlyDictionary<string, object?> ToDictionary(PythonAstNode node) {");
            source.AppendLine("            if (node == null) throw new ArgumentNullException(nameof(node));");
            source.AppendLine("            var result = new Dictionary<string, object?>(StringComparer.Ordinal);");
            source.AppendLine("            foreach (AstFieldValue field in node.GetFields()) {");
            source.AppendLine("                result.Add(field.Name, field.Value);");
            source.AppendLine("            }");
            source.AppendLine("            return result;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public static PythonAstNode FromDictionary(");
            source.AppendLine("            string typeName,");
            source.AppendLine("            IReadOnlyDictionary<string, object?> fields) {");
            source.AppendLine("            if (typeName == null) throw new ArgumentNullException(nameof(typeName));");
            source.AppendLine("            if (fields == null) throw new ArgumentNullException(nameof(fields));");
            source.AppendLine("            return PythonAstFactory.Create(typeName, fields);");
            source.AppendLine("        }");
            source.AppendLine("    }");
        }

        private static void EmitSchemaEntry(
            StringBuilder source,
            string typeName,
            string asdlTypeName,
            string baseClassName,
            IReadOnlyList<AsdlField> fields,
            IReadOnlyList<AsdlField> attributes,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            source.Append("            result.Add(").Append(Quote(typeName)).AppendLine(",");
            source.AppendLine("                new AstTypeMetadata(");
            source.Append("                    ").Append(Quote(typeName)).AppendLine(",");
            source.Append("                    ").Append(Quote(asdlTypeName)).AppendLine(",");
            source.Append("                    ").Append(Quote(baseClassName)).AppendLine(",");
            source.AppendLine("                    new AstFieldMetadata[] {");
            foreach (AsdlField field in fields) {
                EmitFieldMetadata(source, field, false, types);
            }
            foreach (AsdlField attribute in attributes) {
                EmitFieldMetadata(source, attribute, true, types);
            }
            source.AppendLine("                    }));");
        }

        private static void EmitFactory(
            StringBuilder source,
            AsdlModule module,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            source.AppendLine("    public static class PythonAstFactory {");
            source.AppendLine("        public static PythonAstNode Create(");
            source.AppendLine("            string typeName,");
            source.AppendLine("            IReadOnlyDictionary<string, object?> fields) {");
            source.AppendLine("            switch (typeName) {");

            foreach (AsdlTypeDefinition type in module.Types) {
                if (type.IsProduct) {
                    EmitFactoryCase(
                        source,
                        type.Name,
                        BaseClassName(type.Name),
                        type.ProductFields,
                        type.Attributes,
                        types);
                } else {
                    foreach (AsdlConstructor constructor in type.Constructors) {
                        EmitFactoryCase(
                            source,
                            constructor.Name,
                            constructor.Name,
                            constructor.Fields,
                            type.Attributes,
                            types);
                    }
                }
            }

            source.AppendLine("                default:");
            source.AppendLine("                    throw new PythonAstConstructionException(\"Unknown AST node type '\" + typeName + \"'.\");");
            source.AppendLine("            }");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private static void ValidateFields(");
            source.AppendLine("            string typeName,");
            source.AppendLine("            IReadOnlyDictionary<string, object?> fields) {");
            source.AppendLine("            AstTypeMetadata metadata = PythonAstSchema.Types[typeName];");
            source.AppendLine("            var known = new HashSet<string>(metadata.Fields.Select(field => field.Name), StringComparer.Ordinal);");
            source.AppendLine("            foreach (string name in fields.Keys) {");
            source.AppendLine("                if (!known.Contains(name)) {");
            source.AppendLine("                    throw new PythonAstConstructionException(");
            source.AppendLine("                        $\"Unknown AST field '{name}' for node type '{typeName}'.\");");
            source.AppendLine("                }");
            source.AppendLine("            }");
            source.AppendLine("            foreach (AstFieldMetadata field in metadata.Fields) {");
            source.AppendLine("                if (!field.Optional && !fields.ContainsKey(field.Name)) {");
            source.AppendLine("                    throw new PythonAstConstructionException(");
            source.AppendLine("                        $\"Missing required AST field '{field.Name}' for node type '{typeName}'.\");");
            source.AppendLine("                }");
            source.AppendLine("            }");
            source.AppendLine("        }");
            source.AppendLine("    }");
        }

        private static void EmitFactoryCase(
            StringBuilder source,
            string typeName,
            string clrTypeName,
            IReadOnlyList<AsdlField> fields,
            IReadOnlyList<AsdlField> attributes,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            source.Append("                case ").Append(Quote(typeName)).AppendLine(":");
            source.Append("                    ValidateFields(").Append(Quote(typeName)).AppendLine(", fields);");
            source.Append("                    return new ").Append(clrTypeName).AppendLine("(");
            var arguments = new List<string>();
            foreach (AsdlField field in fields) {
                arguments.Add(FactoryArgument(field, types));
            }
            foreach (AsdlField attribute in attributes) {
                arguments.Add(FactoryArgument(attribute, types));
            }
            for (int i = 0; i < arguments.Count; i++) {
                source.Append("                        ").Append(arguments[i])
                    .Append(i + 1 == arguments.Count ? string.Empty : ",").AppendLine();
            }
            source.AppendLine("                    );");
        }

        private static string FactoryArgument(
            AsdlField field,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            string name = Quote(field.Name);
            if (field.Sequence) {
                string elementType = ScalarClrType(field.TypeName, types)
                    + (field.Optional ? "?" : string.Empty);
                return "PythonAstFactorySupport.List<" + elementType + ">(fields, " + name + ")";
            }
            string scalarType = ScalarClrType(field.TypeName, types);
            return field.Optional
                ? "PythonAstFactorySupport.Optional<" + scalarType + ">(fields, " + name + ")"
                : "PythonAstFactorySupport.Required<" + scalarType + ">(fields, " + name + ")";
        }

        private static void EmitFieldMetadata(
            StringBuilder source,
            AsdlField field,
            bool attribute,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            source.Append("                        new AstFieldMetadata(")
                .Append(Quote(field.Name)).Append(", ")
                .Append(Quote(ClrType(field, types))).Append(", ")
                .Append(field.Optional ? "true" : "false").Append(", ")
                .Append(field.Sequence ? "true" : "false").Append(", ")
                .Append(attribute ? "true" : "false")
                .AppendLine("),");
        }

        private static string AttributeArgument(IReadOnlyList<AsdlField> attributes, string name) {
            return attributes.Any(attribute => string.Equals(attribute.Name, name, StringComparison.Ordinal))
                ? EscapeIdentifier(name)
                : "null";
        }

        private static string PropertyName(string name) {
            if (string.Equals(name, "arg", StringComparison.Ordinal)) return "ArgName";
            return PascalizeRaw(name);
        }

        private static string AttributePropertyName(string name) {
            switch (name) {
                case "lineno":
                    return "LineNumber";
                case "col_offset":
                    return "ColumnOffset";
                case "end_lineno":
                    return "EndLineNumber";
                case "end_col_offset":
                    return "EndColumnOffset";
                default:
                    return PropertyName(name);
            }
        }

        private static string PascalizeRaw(string name) {
            string[] parts = name.Split(new[] { '_' }, StringSplitOptions.RemoveEmptyEntries);
            var result = new StringBuilder();
            foreach (string part in parts) {
                result.Append(char.ToUpperInvariant(part[0])).Append(part.Substring(1));
            }
            return result.ToString();
        }

        private static string BaseClassName(string asdlName) {
            return BaseTypeNames.TryGetValue(asdlName, out string? mapped)
                ? mapped
                : Pascalize(asdlName);
        }

        private static string Pascalize(string value) {
            return PascalizeRaw(value);
        }

        private static string ClrType(
            AsdlField field,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            string elementType = ScalarClrType(field.TypeName, types);
            if (field.Optional) elementType += "?";
            return field.Sequence ? "IReadOnlyList<" + elementType + ">" : elementType;
        }

        private static string ScalarClrType(
            string asdlType,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            switch (asdlType) {
                case "identifier":
                case "string":
                    return "string";
                case "int":
                    return "int";
                case "constant":
                    return "object?";
            }
            return types.TryGetValue(asdlType, out AsdlTypeDefinition? type)
                ? BaseClassName(type.Name)
                : Pascalize(asdlType);
        }

        private static bool IsAstReference(
            string asdlType,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            return types.ContainsKey(asdlType);
        }

        private static bool RequiresNullCheck(
            AsdlField field,
            IReadOnlyDictionary<string, AsdlTypeDefinition> types) {
            if (field.Sequence) return true;
            if (field.Optional) return false;
            return field.TypeName != "constant" && field.TypeName != "int";
        }

        private static string EscapeIdentifier(string identifier) {
            return CSharpKeywords.Contains(identifier) ? "@" + identifier : identifier;
        }

        private static string Quote(string value) {
            return "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
        }
    }
}
