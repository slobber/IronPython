using System;
using System.Text;

namespace IronPython.ParserGenerator {
    public static class PegDescriptorEmitter {
        public static string Emit(PegGrammar grammar, string namespaceName, string className) {
            if (grammar == null) throw new ArgumentNullException(nameof(grammar));

            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using IronPython.Compiler.Syntax;");
            source.AppendLine();
            source.Append("namespace ").Append(namespaceName).AppendLine(" {");
            source.Append("    public static class ").Append(className).AppendLine(" {");
            source.AppendLine("        public static readonly PegRuleDescriptor[] Rules = new PegRuleDescriptor[] {");
            foreach (PegGrammarRule rule in grammar.Rules) {
                source.Append("            new PegRuleDescriptor(\"")
                    .Append(Escape(rule.Name))
                    .Append("\", ")
                    .Append(rule.Memo ? "true" : "false")
                    .AppendLine(", new PegAlternativeDescriptor[] {");
                for (int i = 0; i < rule.Alternatives.Count; i++) {
                    PegAlternative alternative = rule.Alternatives[i];
                    source.Append("                new PegAlternativeDescriptor(\"")
                        .Append(Escape(rule.Name + "." + i))
                        .Append("\", new PegElementDescriptor[] {");
                    if (alternative.Elements.Count > 0) source.AppendLine();
                    for (int j = 0; j < alternative.Elements.Count; j++) {
                        source.Append("                    ")
                            .Append(EmitElement(alternative.Elements[j], rule.Name + "." + i + "." + j))
                            .AppendLine(",");
                    }
                    if (alternative.Elements.Count > 0) source.Append("                ");
                    source.Append("}, ")
                        .Append(alternative.EndsWithEof ? "true" : "false")
                        .Append(", ")
                        .Append(alternative.Action is not null ? "true" : "false")
                        .Append(", minimumMinorVersion: ")
                        .Append(PegActionMetadata.ExtractMinimumMinorVersion(alternative.Action))
                        .AppendLine("),");
                }
                source.Append("            }, indirectLeftRecursion: ")
                    .Append(rule.IndirectLeftRecursion ? "true" : "false")
                    .Append(", leftRecursive: ")
                    .Append(rule.LeftRecursive ? "true" : "false")
                    .AppendLine("),");
            }
            source.AppendLine("        };");
            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        private static string EmitElement(PegElement element, string actionPath) {
            string kind = element.Kind switch {
                PegElementKind.Name => "PegDescriptorKind.Name",
                PegElementKind.String => "PegDescriptorKind.String",
                PegElementKind.Group => "PegDescriptorKind.Group",
                PegElementKind.Optional => "PegDescriptorKind.Optional",
                PegElementKind.Repeat => "PegDescriptorKind.Repeat",
                PegElementKind.RepeatOne => "PegDescriptorKind.RepeatOne",
                PegElementKind.Gather => "PegDescriptorKind.Gather",
                PegElementKind.PositiveLookahead => "PegDescriptorKind.PositiveLookahead",
                PegElementKind.NegativeLookahead => "PegDescriptorKind.NegativeLookahead",
                PegElementKind.Cut => "PegDescriptorKind.Cut",
                PegElementKind.Forced => "PegDescriptorKind.Forced",
                _ => throw new ArgumentOutOfRangeException(nameof(element))
            };

            var builder = new StringBuilder("new PegElementDescriptor(").Append(kind);
            if (element.Value is not null) {
                builder.Append(", value: \"").Append(Escape(element.Value)).Append('"');
            }
            if (element.FieldName is not null) {
                builder.Append(", fieldName: \"").Append(Escape(element.FieldName)).Append('"');
            }
            if (element.Child is not null) {
                builder.Append(", child: ").Append(EmitElement(element.Child, actionPath + ".child"));
            }
            if (element.Separator is not null) {
                builder.Append(", separator: ").Append(EmitElement(element.Separator, actionPath + ".separator"));
            }
            if (element.Alternatives is not null) {
                builder.Append(", alternatives: new PegAlternativeDescriptor[] {");
                for (int i = 0; i < element.Alternatives.Count; i++) {
                    PegAlternative alternative = element.Alternatives[i];
                    builder.Append("new PegAlternativeDescriptor(\"")
                        .Append(Escape(actionPath + "." + i))
                        .Append("\", new PegElementDescriptor[] {");
                    for (int j = 0; j < alternative.Elements.Count; j++) {
                        if (j > 0) builder.Append(", ");
                        builder.Append(EmitElement(alternative.Elements[j], actionPath + "." + i + "." + j));
                    }
                    builder.Append("}, ")
                        .Append(alternative.EndsWithEof ? "true" : "false")
                        .Append(", ")
                        .Append(alternative.Action is not null ? "true" : "false")
                        .Append(", minimumMinorVersion: ")
                        .Append(PegActionMetadata.ExtractMinimumMinorVersion(alternative.Action))
                        .Append("),");
                }
                builder.Append('}');
            }
            builder.Append(')');
            return builder.ToString();
        }

        private static string Escape(string value) {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }
    }
}
